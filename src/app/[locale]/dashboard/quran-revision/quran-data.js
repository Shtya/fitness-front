export function ayahAudioUrl(folder, surahId, ayahN) {
	const s = String(surahId).padStart(3, '0');
	const a = String(ayahN).padStart(3, '0');
	return `https://everyayah.com/data/${folder}/${s}${a}.mp3`;
}

export function extractYoutubeId(input) {
	if (!input) return null;
	const str = String(input).trim();
	if (/^[\w-]{11}$/.test(str)) return str;
	try {
		const u = new URL(str);
		if (u.hostname.includes('youtu.be')) return u.pathname.slice(1).split('/')[0] || null;
		if (u.searchParams.get('v')) return u.searchParams.get('v');
		const parts = u.pathname.split('/').filter(Boolean);
		const embedIdx = parts.indexOf('embed');
		if (embedIdx >= 0 && parts[embedIdx + 1]) return parts[embedIdx + 1];
		const shortsIdx = parts.indexOf('shorts');
		if (shortsIdx >= 0 && parts[shortsIdx + 1]) return parts[shortsIdx + 1];
	} catch {
		/* ignore */
	}
	return null;
}

/** Resolve video title without API key (oEmbed / noembed). */
export async function fetchYoutubeTitle(urlOrId) {
	const videoId = extractYoutubeId(urlOrId);
	if (!videoId) return null;
	const watchUrl = `https://www.youtube.com/watch?v=${videoId}`;
	const endpoints = [
		`https://noembed.com/embed?url=${encodeURIComponent(watchUrl)}`,
		`https://www.youtube.com/oembed?url=${encodeURIComponent(watchUrl)}&format=json`,
	];
	for (const endpoint of endpoints) {
		try {
			const res = await fetch(endpoint);
			if (!res.ok) continue;
			const data = await res.json();
			if (data?.title) return String(data.title).trim();
		} catch {
			/* try next */
		}
	}
	return null;
}

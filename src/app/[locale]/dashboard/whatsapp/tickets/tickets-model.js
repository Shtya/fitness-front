/** Your own order, with pinned tickets first. */
export function sortTickets(tickets) {
	return tickets
		.map((t, i) => [t, i])
		.sort(([a, i], [b, j]) => Number(b.pinned) - Number(a.pinned) || i - j)
		.map(([t]) => t);
}

